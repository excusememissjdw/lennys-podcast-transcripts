#!/usr/bin/env python3
"""Export this archive into SQL seed files for Workgraph's Perspectives section.

Usage:
    python3 scripts/export-workgraph-seed.py <path-to-workgraph-repo>

Writes two idempotent migrations into <workgraph>/supabase/migrations/:
  039_seed_lenny_episodes.sql      every episode's metadata (deduplicated by video id)
  040_seed_perspectives_<topic>.sql one per perspectives/<topic>.json file

Re-running is safe: rows are upserted by slug. Requires PyYAML.
"""
import glob
import json
import os
import re
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def q(value):
    """Quote a value as a SQL literal."""
    if value is None or value == "":
        return "null" if value is None else "''"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(int(value))
    return "'" + str(value).replace("'", "''") + "'"


def seconds(stamp):
    total = 0
    for part in stamp.split(":"):
        total = total * 60 + int(part)
    return total


def load_episodes():
    episodes = []
    for path in sorted(glob.glob(os.path.join(ROOT, "episodes", "*", "transcript.md"))):
        slug = path.split(os.sep)[-2]
        text = open(path, encoding="utf-8").read()
        match = re.match(r"^---\n(.*?)\n---\n", text, re.S)
        meta = yaml.safe_load(match.group(1)) if match else {}
        if not str(meta.get("title") or "").strip():
            continue  # placeholders with no title (e.g. teasers) are not real episodes
        meta["slug"] = slug
        meta["_size"] = len(text)
        episodes.append(meta)
    # The archive holds some duplicate copies of the same video under two slugs.
    # Keep the copy with the longest transcript (ties: the shorter slug).
    by_video, unique = {}, []
    for ep in episodes:
        vid = str(ep.get("video_id") or "")
        if not vid:
            unique.append(ep)
            continue
        best = by_video.get(vid)
        if best is None or (ep["_size"], -len(ep["slug"])) > (best["_size"], -len(best["slug"])):
            by_video[vid] = ep
    unique.extend(by_video.values())
    return sorted(unique, key=lambda e: e["slug"])


def episodes_sql(episodes):
    rows = []
    for ep in episodes:
        date = str(ep.get("publish_date") or "")
        desc = re.sub(r"\s+", " ", str(ep.get("description") or "")).strip()
        desc = re.split(r"\s+(?:🎙|—|\*\*|Find the full episode)", desc)[0][:200]
        rows.append("(" + ",".join([
            q(ep["slug"]), q(str(ep.get("guest") or ep["slug"])), q(str(ep.get("title") or "")),
            q(str(ep.get("video_id") or "")),
            (q(date) + "::date") if re.match(r"^\d{4}-\d{2}-\d{2}$", date) else "null",
            q(str(ep.get("duration") or "")), str(int(float(ep.get("duration_seconds") or 0))),
            q(desc),
        ]) + ")")
    return (
        "-- Generated by lennys-podcast-transcripts/scripts/export-workgraph-seed.py. Do not edit by hand.\n"
        "insert into public.workgraph_lenny_episodes\n"
        "  (slug,guest,title,video_id,publish_date,duration,duration_seconds,description)\nvalues\n"
        + ",\n".join(rows)
        + "\non conflict (slug) do update set guest=excluded.guest,title=excluded.title,"
        "video_id=excluded.video_id,publish_date=excluded.publish_date,duration=excluded.duration,"
        "duration_seconds=excluded.duration_seconds,description=excluded.description,updated_at=now();\n"
        "-- The YouTube link is derived from the video id rather than stored twice in this file.\n"
        "update public.workgraph_lenny_episodes set youtube_url=case when video_id='' then '' else 'https://www.youtube.com/watch?v='||video_id end;\n"
    )


def perspectives_sql(data):
    t = data["topic"]
    out = [
        "-- Generated by lennys-podcast-transcripts/scripts/export-workgraph-seed.py from",
        f"-- perspectives/{t['slug']}.json. Do not edit by hand.",
        f"insert into public.workgraph_lenny_topics(slug,name,description) values ({q(t['slug'])},{q(t['name'])},{q(t['description'])})",
        "on conflict (slug) do update set name=excluded.name,description=excluded.description;",
    ]
    for slug, (stage, model, role, org) in data.get("guest_context", {}).items():
        out.append(
            f"update public.workgraph_lenny_episodes set company_stage={q(stage)},business_model={q(model)},"
            f"guest_role={q(role)},guest_org={q(org)},updated_at=now() where slug={q(slug)};"
        )
    for i, d in enumerate(data["debates"]):
        out.append(
            "insert into public.workgraph_lenny_debates(topic_id,slug,question,left_label,left_summary,right_label,right_summary,insight,sort_order)\n"
            f"select id,{q(d['slug'])},{q(d['question'])},{q(d['left_label'])},{q(d['left_summary'])},{q(d['right_label'])},"
            f"{q(d['right_summary'])},{q(d['insight'])},{i} from public.workgraph_lenny_topics where slug={q(t['slug'])}\n"
            "on conflict (slug) do update set topic_id=excluded.topic_id,question=excluded.question,left_label=excluded.left_label,"
            "left_summary=excluded.left_summary,right_label=excluded.right_label,right_summary=excluded.right_summary,"
            "insight=excluded.insight,sort_order=excluded.sort_order,updated_at=now();"
        )
        values = ",\n".join(
            f"  ({q(p['episode'])},{p['position']},{q(p['stance'])},{q(p['quote'])},{seconds(p['time'])})"
            for p in d["positions"]
        )
        out.append(
            "insert into public.workgraph_lenny_positions(debate_id,episode_id,position,stance,quote,timestamp_seconds)\n"
            "select d.id,e.id,v.position,v.stance,v.quote,v.ts from (values\n"
            + values
            + f"\n) as v(slug,position,stance,quote,ts)\njoin public.workgraph_lenny_episodes e on e.slug=v.slug\n"
            f"cross join (select id from public.workgraph_lenny_debates where slug={q(d['slug'])}) d\n"
            "on conflict (debate_id,episode_id) do update set position=excluded.position,stance=excluded.stance,"
            "quote=excluded.quote,timestamp_seconds=excluded.timestamp_seconds;"
        )
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    migrations = os.path.join(sys.argv[1], "supabase", "migrations")
    episodes = load_episodes()
    with open(os.path.join(migrations, "039_seed_lenny_episodes.sql"), "w", encoding="utf-8") as f:
        f.write(episodes_sql(episodes))
    print(f"039_seed_lenny_episodes.sql: {len(episodes)} episodes")
    for path in sorted(glob.glob(os.path.join(ROOT, "perspectives", "*.json"))):
        data = json.load(open(path, encoding="utf-8"))
        name = f"040_seed_perspectives_{data['topic']['slug'].replace('-', '_')}.sql"
        with open(os.path.join(migrations, name), "w", encoding="utf-8") as f:
            f.write(perspectives_sql(data))
        print(f"{name}: {len(data['debates'])} debates")


if __name__ == "__main__":
    main()
